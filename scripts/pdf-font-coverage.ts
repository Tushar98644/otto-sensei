// Writes src/lib/pdf/font-coverage.ts: which characters each bundled PDF font can draw, read from
// the font files in public/fonts/pdf. Re-run it after adding or swapping a font file:
//
//   bun scripts/pdf-font-coverage.ts
//
// A family covers a character only when every face of it does (a name in bold must still print).

import { writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { PDF_FONT_FAMILIES, PDF_FONT_NAMES, type PdfFontName } from "../src/lib/pdf/fonts";

type FontkitFont = { characterSet: number[] };
const fontkit = createRequire(import.meta.url)("fontkit") as {
  openSync: (path: string) => FontkitFont;
};

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUT = join(ROOT, "src", "lib", "pdf", "font-coverage.ts");

// Controls, private use and the like never count as drawable, whatever a font maps them to.
const PRINTABLE = /^[\p{L}\p{M}\p{N}\p{P}\p{S}\p{Zs}]$/u;

const intersect = (sets: Set<number>[]): Set<number> =>
  sets.reduce((all, set) => new Set([...all].filter((code) => set.has(code))));

function familyCoverage(name: PdfFontName): Set<number> {
  const family = PDF_FONT_FAMILIES[name];
  const faces = family.faces.map((face) => {
    const file = join(ROOT, "public", "fonts", "pdf", family.dir, face.file);
    return new Set(fontkit.openSync(file).characterSet);
  });
  return new Set(
    [...intersect(faces)].filter((code) => PRINTABLE.test(String.fromCodePoint(code))),
  );
}

// [start, end, start, end, ...], inclusive and sorted.
function ranges(set: Set<number>): number[] {
  const codes = [...set].sort((a, b) => a - b);
  const out: number[] = [];
  for (const code of codes) {
    if (out.length > 0 && out[out.length - 1] === code - 1) out[out.length - 1] = code;
    else out.push(code, code);
  }
  return out;
}

function format(list: number[]): string {
  const lines: string[] = [];
  for (let i = 0; i < list.length; i += 16) lines.push(`    ${list.slice(i, i + 16).join(", ")},`);
  return `[\n${lines.join("\n")}\n  ]`;
}

async function main() {
  const coverage = new Map(PDF_FONT_NAMES.map((name) => [name, familyCoverage(name)]));
  // What every family prints, with its fallback drawing the gaps: the characters a resume keeps in
  // any format.
  const drawable = intersect(
    PDF_FONT_NAMES.map((name) => {
      const own = coverage.get(name)!;
      const fallback = PDF_FONT_FAMILIES[name].fallback;
      return fallback ? new Set([...own, ...coverage.get(fallback)!]) : own;
    }),
  );
  const body = [
    "// Generated by scripts/pdf-font-coverage.ts from the files in public/fonts/pdf. Don't edit by",
    "// hand: re-run the script after changing a font.",
    "",
    'import type { PdfFontName } from "./fonts";',
    "",
    "// Inclusive code point ranges, flattened: [start, end, start, end, ...].",
    "export type CoverageRanges = readonly number[];",
    "",
    "/** What each family draws in every one of its faces. */",
    "export const FAMILY_COVERAGE: Record<PdfFontName, CoverageRanges> = {",
    ...PDF_FONT_NAMES.map(
      (name) => `  ${JSON.stringify(name)}: ${format(ranges(coverage.get(name)!))},`,
    ),
    "};",
    "",
    "/** What every format prints, counting each family's fallback. */",
    `export const DRAWABLE: CoverageRanges = ${format(ranges(drawable))};`,
    "",
  ].join("\n");
  await writeFile(OUT, body);
  console.log(`Wrote ${OUT}: ${drawable.size} drawable characters`);
  for (const name of PDF_FONT_NAMES) console.log(`  ${name}: ${coverage.get(name)!.size}`);
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
