const OTHER_COMPANIES = [
  "Harrowgate Mobile",
  "Pinebrook Systems",
  "Calloway Freight",
  "Bluefen Studio",
  "Ostrander Health",
  "Mirelock Bank",
];
const OTHER_PLACES = ["Remote", "Austin, TX", "Toronto, ON", "Chicago, IL", "Denver, CO"];

function listings(count: number, offset: number): string {
  return Array.from({ length: count }, (_, index) => {
    const at = index + offset;
    const title = OTHER_TITLES[at % OTHER_TITLES.length];
    const company = OTHER_COMPANIES[(at * 7) % OTHER_COMPANIES.length];
    const place = OTHER_PLACES[(at * 3) % OTHER_PLACES.length];
    return `${title}\n${company} · ${place} · Posted ${(at % 28) + 1} days ago · Save`;
  }).join("\n");
}

