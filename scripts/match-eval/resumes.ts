function workIn(
  country: string,
  timeZone: string,
  rights: Partial<WorkProfile["rights"]>,
): WorkProfile {
  return {
    ...emptyWorkProfile(),
    country,
    timeZone,
    rights: { ...emptyWorkProfile().rights, ...rights },
  };
}

