export type TestResume = {
  id: string;
  field: "engineering" | "data" | "product" | "design" | "sales" | "support" | "operations";
  level: "junior" | "mid" | "senior";
  // Where they live and may work, in words for the judge and as a work profile for the rules.
  place: string;
  work: WorkProfile;
  // Newest first, as a resume lists them.
  titles: string[];
  years: number;
  // What the browser would read skills from: the summary, the job lines and the skills section.
  text: string;
};

function workIn(
  country: string,
  timeZone: string,
  rights: Partial<WorkProfile["rights"]>,
): WorkProfile {
  return {
    ...emptyWorkProfile(),
    country,
    timeZone,
    rights: { ...emptyWorkProfile().rights, ...rights },
  };
}

